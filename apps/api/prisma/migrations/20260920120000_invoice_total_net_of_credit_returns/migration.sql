-- مبلغِ فاکتور، منهای مرجوعی‌های اعتباری‌اش — یک‌بار برای همیشه.
--
-- چرا: تا امروز مرجوعیِ اعتباری فقط `dueAmount` را کم می‌کرد و به `total` دست
-- نمی‌زد. نتیجه اینکه `total` فاکتورهای مرجوعی‌خورده کهنه می‌ماند (فاکتوری که
-- ۳۰ فروخته، ۲۰ مرجوعی خورده و ۱۰ اصلاحیه گرفته، «۴۰» بود به‌جای «۲۰») و هر
-- مصرف‌کننده مجبور بود دلتای مرجوعی را خودش اضافه کند — یکی این کار را می‌کرد
-- و دیگری نه، و همان ناهم‌خوانی روی صفحه‌ها بیرون می‌زد.
--
-- از این پس خودِ برنامه `total` را هم کم می‌کند (returns.service)؛ این مهاجرت
-- فاکتورهای موجود را با همان قاعده یک‌جا صاف می‌کند تا عددِ ذخیره‌شده با عددی
-- که صفحه‌ها نشان می‌دهند یکی باشد.
--
-- منبعِ بازمحاسبه: ردیف‌های دفترِ همان فاکتور (`type = 'RETURN'`، مبلغ منفی).
-- مرجوعیِ نقد/کارت ردیفِ دفتر ندارد، پس دست نمی‌خورد — دقیقاً همان مرزی که در
-- کد گذاشته شده. شرطِ `GREATEST(…, 0)` هم فقط نگهبان است: مبلغ فاکتور هرگز
-- نباید منفی بماند.
UPDATE "SaleInvoice" AS i
SET "total" = GREATEST(
  0,
  i."total" + COALESCE(
    (
      SELECT SUM(l."amount")::int
      FROM "CustomerLedger" AS l
      WHERE l."invoiceId" = i."id" AND l."type" = 'RETURN'
    ),
    0
  )
)
WHERE EXISTS (
  SELECT 1
  FROM "CustomerLedger" AS l
  WHERE l."invoiceId" = i."id" AND l."type" = 'RETURN'
);
