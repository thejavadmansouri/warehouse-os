/**
 * تصمیمِ «مکانِ ردیف‌های فاکتور فروش» — جدا از سرویس تا سیاستش یک‌جا بنشیند و
 * قابلِ تست باشد (همان کاری که `line-balance.ts` و `return-pricing.ts` می‌کنند).
 *
 * ═══ سیاستِ امروز ═══
 *
 * ۱. **انبارِ فاکتور یک سربرگ است، نه قیدِ موجودی.** قلمِ فاکتور می‌تواند از
 *    قفسه‌ی انبارِ دیگر بیاید.
 *
 *    تا شهریور، اینجا یک قاعده‌ی «قفسهٔ فعالِ انبارِ دیگر ممنوع» بود و فاکتور با
 *    `LOCATION_NOT_IN_WAREHOUSE` رد می‌شد. آن قاعده برای زمان خودش درست بود:
 *    `locationId` مستقیم از کلاینت می‌رفت و چون فروش با `allowNegative` اجرا
 *    می‌شود، فاکتورِ انبار A می‌توانست موجودیِ قفسه‌ای در انبار B را بی‌صدا منفی
 *    کند. اما در مغازه، انبارها پشتِ یک پیشخوان‌اند و فروشنده جنس را از همان‌جا
 *    برمی‌دارد: یک خرید = یک فاکتور، حتی اگر اقلامش از دو قفسه‌ی دو انبار
 *    بیایند. صندوق هم قفسه را خودکار از **پرموجودی‌ترین** مکان انتخاب می‌کند،
 *    پس قاعده بیشتر وقت‌ها بی‌آنکه کسی چیزی را عوض کند فاکتور را رد می‌کرد.
 *
 *    منبعِ حقیقت برای موجودی، **قفسه‌ی همان ردیف** است: هر ردیف یک رکوردِ
 *    `InventoryLog` با `locationId` خودش است، پس موجودیِ درست کم می‌شود و
 *    مرجوعی هم به همان قفسه برمی‌گردد. انبارِ سربرگ برای فیلترِ فهرست فاکتورها
 *    و سربرگِ مرجوعی/اصلاحیه می‌ماند. روی برگه‌ی مشتری هم انبار چاپ نمی‌شود؛
 *    مسیرِ کاملِ قفسه (که با کدِ انبار شروع می‌شود) فقط در نمای داخلی دیده می‌شود.
 *
 * ۲. **قفسه‌ی غیرفعال/حذف‌شده مجاز است.** حذفِ قفسه‌ی دارای موجودی فقط
 *    غیرفعالش می‌کند و جنس رویش «بی‌صاحب» می‌ماند؛ این جنس فیزیکاً هست و باید
 *    فروختنی بماند.
 *
 * ۳. **قفسه‌ای که اصلاً رکورد ندارد فقط اگر موجودیِ همان کالا رویش باشد.**
 *    وگرنه `upsert`ِ فروش می‌خواهد ردیفِ موجودی روی مکانی بسازد که وجود ندارد و
 *    خطای کلید خارجی می‌دهد — این تور آن را با پیام روشن می‌گیرد نه با ۵۰۰.
 *
 * ۴. ردیفِ **بدون** قفسه (کالایی که هنوز وارد نرم‌افزار نشده) کارِ این ماژول
 *    نیست؛ آن روی مکانِ سیستمیِ «موجودی ثبت‌نشده» می‌نشیند.
 */

/** ردیفی که قفسه دارد؛ همان چیزی که باید اعتبارسنجی شود. */
export interface SaleLineRef {
  /** اندیسِ ردیف در همان ترتیبی که کلاینت فرستاده — برای پیامِ خطای دقیق. */
  index: number;
  productId: string;
  locationId: string;
}

/** کلیدِ یکتای «کالا روی قفسه» — همان شکلی که در کوئریِ موجودی ساخته می‌شود. */
export function inventoryKey(productId: string, locationId: string): string {
  return `${productId}::${locationId}`;
}

/** ردیف‌های صاحبِ قفسه. ردیفِ بدون قفسه اینجا نمی‌آید (سیاست ۴). */
export function saleLineRefs(
  lines: { productId: string; locationId?: string | null }[],
): SaleLineRef[] {
  const refs: SaleLineRef[] = [];
  lines.forEach((line, index) => {
    if (!line.locationId) return;
    refs.push({
      index,
      productId: line.productId,
      locationId: line.locationId,
    });
  });
  return refs;
}

/**
 * ردیف‌هایی که قفسه‌شان رکوردی در دیتابیس ندارد.
 *
 * عمداً درباره‌ی انبار هیچ سؤالی نمی‌پرسد — همین نبودِ سؤال، خودِ سیاستِ ۱ است.
 */
export function locationsWithoutRecord(
  refs: SaleLineRef[],
  knownLocationIds: Set<string>,
): SaleLineRef[] {
  return refs.filter((ref) => !knownLocationIds.has(ref.locationId));
}

/**
 * اولین ردیفی که قفسه‌اش نه رکورد دارد و نه موجودی — یعنی «مکانِ ساختگی».
 * null یعنی همه‌ی قفسه‌های بی‌رکورد، واقعاً جنس رویشان نشسته.
 */
export function firstWithoutInventory(
  refs: SaleLineRef[],
  stockedPairs: Set<string>,
): SaleLineRef | null {
  return (
    refs.find(
      (ref) => !stockedPairs.has(inventoryKey(ref.productId, ref.locationId)),
    ) ?? null
  );
}
