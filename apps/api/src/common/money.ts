/**
 * سقفِ مبلغ هر سند — ستون‌های پول float8 (double precision) هستند.
 *
 * JS تا 2^53 ≈ 9×10¹⁵ عدد صحیح دقیق را نشان می‌دهد؛ سقفِ عملیِ هر سند را
 * چند پله پایین‌تر نگه می‌داریم — برای اطمینان از اینکه جمع‌های داخلی
 * (مثلاً جمعِ ردیف‌های یک فاکتور ۵۰۰ قلمی) هم در ناحیه‌ی دقیق بمانند.
 *
 * ۱۰¹² ریال = ۱۰۰ میلیارد تومان — هزار برابرِ سقفِ قبلیِ INT4.
 */
export const INT4_MAX = 1_000_000_000_000; // 1e12 rial = 100 billion toman

/**
 * واحد پول. رابطه ثابت است: ۱ تومان = ۱۰ ریال.
 *
 * عمداً از `@prisma/client` وارد نمی‌شود تا این فایل بدون تولید کلاینت هم قابل
 * تست باشد؛ مقادیر همان enum پایگاه‌داده‌اند.
 */
export type CurrencyUnit = 'RIAL' | 'TOMAN';

/** برچسبی که کنار عدد چاپ می‌شود. */
export function unitLabel(unit: CurrencyUnit): string {
  return unit === 'TOMAN' ? 'تومان' : 'ریال';
}

/**
 * تبدیل مبلغ بین دو واحد — **فقط برای نمایش**.
 *
 * عددِ ذخیره‌شده هرگز با این تابع بازنویسی نمی‌شود؛ این تابع در لبه‌ی خروجی
 * صدا زده می‌شود و نتیجه‌اش به کاربر می‌رسد، نه به دیتابیس.
 *
 * ⚠️ ریال → تومان تقسیم بر ۱۰ است و رقم آخر ریال را از دست می‌دهد
 * (۱۸۵٬۰۰۵ ریال → ۱۸٬۵۰۱ تومان). برای اینکه فاکتور مشتری جمع بخورد، قاعده
 * این است: **اول قیمت هر ردیف تبدیل شود، بعد جمع زده شود** — نه برعکس.
 * جمعِ تبدیل‌شده‌ها با تبدیلِ جمع لزوماً برابر نیست، و آن چیزی که مشتری با
 * ماشین‌حساب چک می‌کند ستونِ ردیف‌هاست.
 */
export function convertMoney(
  value: number,
  from: CurrencyUnit,
  to: CurrencyUnit,
): number {
  if (from === to) return value;
  return from === 'RIAL' ? Math.round(value / 10) : value * 10;
}
