/**
 * ترتیبِ ثابتِ قفل‌گیری برای عملیاتِ چندردیفیِ انبار.
 *
 * ### مشکلی که حل می‌کند
 *
 * هر حرکتِ موجودی روی سطرِ `Inventory` با کلیدِ `(productId, locationId)` قفل
 * می‌گیرد. یک فاکتورِ چندردیفی این قفل‌ها را **یکی‌یکی و به ترتیبی که کلاینت
 * فرستاده** می‌گیرد و تا پایانِ تراکنش نگه می‌دارد.
 *
 * حالا دو صندوق را هم‌زمان در نظر بگیر:
 *
 * - صندوقِ ۱ کالای A را می‌فروشد و بعد B → قفلِ A را دارد، منتظرِ B است.
 * - صندوقِ ۲ همان دو کالا را به ترتیبِ B و بعد A فروخته → قفلِ B را دارد،
 *   منتظرِ A است.
 *
 * هیچ‌کدام رها نمی‌کند. پستگرس یکی را با خطای deadlock می‌کشد و فروشنده یک
 * خطای نامفهوم می‌بیند که هیچ‌وقت نمی‌تواند دوباره تولیدش کند — چون به ترتیبِ
 * اقلام در سبد و هم‌زمانیِ دقیقِ دو صندوق بستگی دارد.
 *
 * ### راهِ حل
 *
 * اگر **همه‌ی** تراکنش‌ها قفل‌ها را با یک ترتیبِ یکسان بگیرند، حلقه‌ی انتظار
 * اصلاً تشکیل نمی‌شود: صندوقِ دوم پشتِ اولین قفلِ مشترک می‌ایستد و بعد از
 * commitِ صندوقِ اول عبور می‌کند. کندتر نیست — فقط منتظر می‌ماند به‌جای اینکه
 * بمیرد.
 *
 * ترتیب چه باشد مهم نیست، فقط باید **همه‌جا یکی** باشد. اینجا `productId` و بعد
 * `locationId` انتخاب شده چون همان کلیدِ یکتای سطرِ قفل‌شونده است.
 *
 * ### چرا کپی برمی‌گرداند
 *
 * ترتیبِ اصلیِ ردیف‌ها معنای خودش را دارد — `lineIndex` در خطای کمبودِ موجودی
 * به همان اشاره می‌کند تا صندوق بداند کدام سطر را قرمز کند. پس آرایه‌ی ورودی
 * هرگز جابه‌جا نمی‌شود؛ فقط برای پیمایشِ قفل‌گیری یک کپیِ مرتب ساخته می‌شود.
 *
 * ⚠️ `locationId` باید **مقدارِ نهایی و resolve‌شده** باشد، نه آنچه کلاینت
 * فرستاده. ردیفِ بی‌مکان که روی «انبار موقت» یا «موجودیِ ثبت‌نشده» می‌نشیند،
 * قفلِ همان مکانِ سیستمی را می‌گیرد — پس مرتب‌سازی هم باید با همان انجام شود،
 * وگرنه ترتیب فقط ظاهراً ثابت است.
 */

/** حداقلِ چیزی که برای تعیینِ ترتیبِ قفل لازم است. */
export interface LockKey {
  productId: string;
  /** مکانِ resolve‌شده. `null` برای حرکاتی که هنوز مکان ندارند. */
  locationId?: string | null;
}

/**
 * کپیِ مرتب‌شده‌ی `items` به ترتیبِ قفل‌گیری. ورودی دست‌نخورده می‌ماند.
 *
 * @param key اگر ردیف خودش `productId`/`locationId` ندارد (مثلاً داخلِ یک
 *   wrapper با اندیسِ اصلی نشسته) با این تابع کلیدش استخراج می‌شود.
 */
export function inLockOrder<T extends LockKey>(items: readonly T[]): T[];
export function inLockOrder<T>(items: readonly T[], key: (item: T) => LockKey): T[];
export function inLockOrder<T>(
  items: readonly T[],
  key: (item: T) => LockKey = (item) => item as unknown as LockKey,
): T[] {
  return [...items].sort((a, b) => {
    const ka = key(a);
    const kb = key(b);

    if (ka.productId !== kb.productId) {
      return ka.productId < kb.productId ? -1 : 1;
    }

    // مکانِ نداشته همیشه اولِ گروهِ همان کالا می‌آید — مهم این است که قاعده
    // در همه‌ی تراکنش‌ها یکی باشد، نه اینکه کدام اول باشد.
    const la = ka.locationId ?? '';
    const lb = kb.locationId ?? '';

    if (la === lb) return 0;
    return la < lb ? -1 : 1;
  });
}
