function tocHtml(pages = {}) {
  const rows = CHAPTERS.map((c) => {
    const pg = pages[c.id];
    return `<a><span class="t">${c.label}</span><span class="pg">${pg ? fa(pg) : '—'}</span></a>`;
  }).join('');
  return `
  <div class="chapter">
    <h2 style="border-bottom-color:#0f766e"><span class="num">ف</span>فهرست مطالب</h2>
    <div class="toc">${rows}</div>
    <div class="hr"></div>
    <p class="small">
      این سند ۹ بخش دارد. فصل ۶ قلب سند است: اگر برای خواندن یک فصل وقت دارید،
      همان را بخوانید. جدول‌های مالی همه از یک مدل واحد می‌آید و در پیوست الف
      روش محاسبه آمده است.
    </p>
    <p class="small">
      واحد همهٔ ارقام مالی: میلیون تومان. ارقام به قیمت ثابت سال پایه (۱۴۰۵) است.
    </p>
  </div>`;
}

const buildDoc = (pages) =>
  renderDocument({ title, body: cover + tocHtml(pages) + CHAPTERS.map((c) => c.html).join('') });

async function renderAndCount(name, pages) {
  const htmlPath = writeHtml(`${name}.html`, buildDoc(pages));
  const pdfPath = join(OUT, `${name}.pdf`);
  await printPdfNumbered(htmlPath, pdfPath, { footerLabel: 'طرح توجیهی کاردو — سامانهٔ انبارداری' });
  return countPages(pdfPath);
}

const FOOTER = 'طرح توجیهی کاردو — سامانهٔ انبارداری';

/** سندِ «تا فصلِ n» — برای اندازه‌گیریِ پایانِ آن فصل. */
const docUpTo = (pages, n) =>
  renderDocument({
    title,
    body: cover + tocHtml(pages) + CHAPTERS.slice(0, n).map((c) => c.html).join(''),
  });

/** چاپ یک سند و برگرداندن تعداد صفحه‌ها. */
async function countDoc(pages, n) {
  const htmlPath = writeHtml('_measure.html', docUpTo(pages, n));
  const pdfPath = join(OUT, '_measure.pdf');
  await printPdfNumbered(htmlPath, pdfPath, { footerLabel: FOOTER });
  return countPages(pdfPath);
}

async function main() {
  prepareOutDir();

  const pages = {};

  // ۱) صفحه‌های پیش از فصل اول: جلد + فهرست. فصل‌ها با شکست صفحه شروع می‌شوند،
  //    پس صفحهٔ شروع فصل اول = این تعداد + ۱.
  let cursor = await countDoc(pages, 0);

  // ۲) چاپ تدریجی: پایانِ هر فصل = تعداد صفحه‌های سندِ شاملِ همان فصل.
  for (let i = 0; i < CHAPTERS.length; i++) {
    pages[CHAPTERS[i].id] = cursor + 1;
    cursor = await countDoc(pages, i + 1);
  }

  // ۳) سند نهایی با شماره‌های واقعی
  const finalHtml = writeHtml('kardo-feasibility.html', buildDoc(pages));
  const finalPdf = join(OUT, 'kardo-feasibility.pdf');
  await printPdfNumbered(finalHtml, finalPdf, { footerLabel: FOOTER });

  const total = countPages(finalPdf);
  console.log('صفحهٔ شروع فصل‌ها:', pages);
  console.log('جمع صفحه‌ها:', total);

  for (const f of ['_measure.html', '_measure.pdf']) {
    const p = join(OUT, f);
    if (existsSync(p)) unlinkSync(p);
  }
}

await main();
