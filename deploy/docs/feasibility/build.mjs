/** نمودار ستونیِ گروهی (SVG، بدون کتابخانه). */
function barChart({ labels, series, width = 660, height = 250, money = true, caption = '' }) {
  const pad = { top: 26, right: 12, bottom: 34, left: 58 };
  const w = width - pad.left - pad.right;
  const h = height - pad.top - pad.bottom;
  const max = Math.max(...series.flatMap((s) => s.values), 1);
  const step = Math.ceil(max / 4 / 5000) * 5000 || 1;
  const top = step * 4;
  const groupW = w / labels.length;
  const barW = Math.min(26, (groupW - 16) / series.length);
  const yOf = (v) => pad.top + h - (v / top) * h;
  const ticks = [0, 1, 2, 3, 4].map((i) => i * step);
  const round = (n) => Math.round(n / 1000) * 1000;

  const grid = ticks
    .map(
      (t) =>
        `<line x1="${pad.left}" y1="${yOf(t)}" x2="${pad.left + w}" y2="${yOf(t)}" stroke="#e2e8f0" stroke-width="0.7"/>` +
        `<text x="${pad.left - 5}" y="${yOf(t) + 3.5}" font-size="8" fill="#64748b" text-anchor="end">${fa(round(t))}</text>`,
    )
    .join('');

  const bars = labels
    .map((lab, gi) => {
      const cx = pad.left + w - groupW * (gi + 0.5); // راست‌به‌چپ
      const total = series.length * barW + (series.length - 1) * 4;
      return series
        .map((s, si) => {
          const v = s.values[gi];
          const x = cx - total / 2 + si * (barW + 4);
          const yTop = yOf(Math.max(v, 0));
          const hh = Math.abs(yOf(v) - yOf(0));
          return `<rect x="${x}" y="${yTop}" width="${barW}" height="${Math.max(hh, 0.5)}" fill="${s.color}" rx="1.5"/>`;
        })
        .join('');
    })
    .join('');

  const xLabels = labels
    .map((lab, gi) => {
      const cx = pad.left + w - groupW * (gi + 0.5);
      return `<text x="${cx}" y="${pad.top + h + 18}" text-anchor="middle" font-size="9.5" fill="#334155">${lab}</text>`;
    })
    .join('');

  const legend = series
    .map((s, i) => {
      const x = pad.left + 6 + i * 108;
      return `<rect x="${x}" y="6" width="9" height="9" rx="2" fill="${s.color}"/><text x="${x + 13}" y="14" font-size="9" fill="#334155" text-anchor="start">${s.label}</text>`;
    })
    .join('');

  return `<svg class="chart" viewBox="0 0 ${width} ${height}" width="100%" role="img" aria-label="${
    money ? 'نمودار مالی' : 'نمودار'
  }">
    ${legend}${grid}${bars}${xLabels}
    <line x1="${pad.left}" y1="${yOf(0)}" x2="${pad.left + w}" y2="${yOf(0)}" stroke="#94a3b8" stroke-width="0.9"/>
  </svg>${caption ? `<div class="figcap">${caption}</div>` : ''}`;
}

/** نمودار خطیِ تجمعی (برای دورهٔ بازگشت سرمایه). */
function lineChart({ labels, values, width = 660, height = 200, caption = '' }) {
  const pad = { top: 18, right: 14, bottom: 30, left: 58 };
  const w = width - pad.left - pad.right;
  const h = height - pad.top - pad.bottom;
  const min = Math.min(...values, 0);
  const max = Math.max(...values, 0);
  const span = max - min || 1;
  const yOf = (v) => pad.top + h - ((v - min) / span) * h;
  const step = w / (values.length - 1);
  const pts = values.map((v, i) => `${pad.left + w - i * step},${yOf(v)}`).join(' ');
  const zero = yOf(0);
  const dots = values
    .map(
      (v, i) =>
        `<circle cx="${pad.left + w - i * step}" cy="${yOf(v)}" r="3" fill="${v >= 0 ? '#0f766e' : '#b45309'}"/>` +
        `<text x="${pad.left + w - i * step}" y="${yOf(v) + (v >= 0 ? -8 : 14)}" text-anchor="middle" font-size="8" fill="#475569">${fa(Math.round(v))}</text>`,
    )
    .join('');
  const xs = labels
    .map(
      (l, i) =>
        `<text x="${pad.left + w - i * step}" y="${height - 8}" text-anchor="middle" font-size="9" fill="#334155">${l}</text>`,
    )
    .join('');
  return `<svg class="chart" viewBox="0 0 ${width} ${height}" width="100%">
    <line x1="${pad.left}" y1="${zero}" x2="${pad.left + w}" y2="${zero}" stroke="#94a3b8" stroke-width="0.9" stroke-dasharray="3 3"/>
    <polyline points="${pts}" fill="none" stroke="#14213d" stroke-width="2"/>
    ${dots}${xs}
    <text x="4" y="${zero + 3}" font-size="8" fill="#64748b">صفر</text>
  </svg>${caption ? `<div class="figcap">${caption}</div>` : ''}`;
}

